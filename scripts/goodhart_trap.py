def plant() -> None:
    text = HACKED.format(mode="plant: assert-free tests", imports="")
    DEMO_FILE.write_text(text, encoding="utf-8")
    print(f"Planted assert-free tests in {DEMO_FILE.relative_to(ROOT)}")


def fix() -> None:
    text = HONEST.format(mode="fix: asserting tests", imports=HONEST_IMPORTS)
    DEMO_FILE.write_text(text, encoding="utf-8")
    print(f"Replaced them with asserting tests in {DEMO_FILE.relative_to(ROOT)}")


def clean() -> None:
    DEMO_FILE.unlink(missing_ok=True)
    print("Goodhart-trap demo test removed")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("action", choices=["plant", "fix", "clean"])
    {"plant": plant, "fix": fix, "clean": clean}[parser.parse_args().action]()


if __name__ == "__main__":
    main()
