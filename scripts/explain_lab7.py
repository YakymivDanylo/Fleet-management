"""Lab 7: EXPLAIN (ANALYZE, BUFFERS) of the indexed queries, before and after the new indexes.

    python scripts/explain_lab7.py --out docs/lab7-performance/explain.md

Runs psql inside the compose `db` container (the database port is not published). It loads a
bulk data set (rows tagged EX-/ex-), drops the Lab 7 indexes, explains each query, recreates the
indexes, explains again, and finally removes the bulk data. Run it against the sandbox stack only.
"""

import argparse
import subprocess
from pathlib import Path

STATIONS, VEHICLES, RENTERS, RENTALS = 200, 100_000, 2_000, 400_000

SEED = f"""
INSERT INTO stations (address, capacity)
SELECT 'ex-station-' || g, 1000 FROM generate_series(1, {STATIONS}) g;

INSERT INTO vehicles (license_plate, model, status, station_id)
SELECT 'EX-' || g, 'Bulk Car',
       (ARRAY['AVAILABLE','RENTED','MAINTENANCE'])[1 + g % 3]::vehiclestatus,
       (SELECT min(id) FROM stations WHERE address LIKE 'ex-station-%') + g % {STATIONS}
FROM generate_series(1, {VEHICLES}) g;

INSERT INTO renters (full_name, license_number)
SELECT 'Bulk Renter ' || g, 'EX-LIC-' || g FROM generate_series(1, {RENTERS}) g;

INSERT INTO rentals (renter_id, vehicle_id, start_station_id, started_at, ended_at, status)
SELECT (SELECT min(id) FROM renters WHERE license_number LIKE 'EX-LIC-%') + g % {RENTERS},
       (SELECT min(id) FROM vehicles WHERE license_plate LIKE 'EX-%') + g % {VEHICLES},
       (SELECT min(id) FROM stations WHERE address LIKE 'ex-station-%') + g % {STATIONS},
       now() - (g || ' minutes')::interval,
       now() - (g || ' minutes')::interval + interval '30 minutes',
       'COMPLETED'
FROM generate_series(1, {RENTALS}) g;

ANALYZE stations; ANALYZE vehicles; ANALYZE renters; ANALYZE rentals;
"""

CLEANUP = """
DELETE FROM rentals WHERE renter_id IN (
    SELECT id FROM renters WHERE license_number LIKE 'EX-LIC-%'
);
DELETE FROM renters WHERE license_number LIKE 'EX-LIC-%';
DELETE FROM vehicles WHERE license_plate LIKE 'EX-%';
DELETE FROM stations WHERE address LIKE 'ex-station-%';
"""

DROP_INDEXES = """
DROP INDEX IF EXISTS ix_vehicles_station_id_status;
DROP INDEX IF EXISTS ix_rentals_renter_id_started_at;
ANALYZE vehicles; ANALYZE rentals;
"""

CREATE_INDEXES = """
CREATE INDEX IF NOT EXISTS ix_vehicles_station_id_status ON vehicles (station_id, status);
CREATE INDEX IF NOT EXISTS ix_rentals_renter_id_started_at ON rentals (renter_id, started_at);
ANALYZE vehicles; ANALYZE rentals;
"""

# (title, where it comes from, SQL). The ids are picked inside the SQL so the script needs no state.
QUERIES = [
    (
        "Station occupancy: vehicles parked at a station",
        "`station_service.count_parked_vehicles`, called on every rental return",
        "SELECT count(*) FROM vehicles WHERE station_id = (SELECT min(id) + 7 FROM stations "
        "WHERE address LIKE 'ex-station-%') AND status != 'RENTED'",
    ),
    (
        "A renter's rentals, newest first",
        "`GET /me/rentals`",
        "SELECT * FROM rentals WHERE renter_id = (SELECT min(id) + 7 FROM renters "
        "WHERE license_number LIKE 'EX-LIC-%') ORDER BY started_at DESC",
    ),
]


def psql(sql: str) -> str:
    result = subprocess.run(
        [
            "docker",
            "compose",
            "exec",
            "-T",
            "db",
            "sh",
            "-c",
            'psql -q -X -U "$POSTGRES_USER" -d "$POSTGRES_DB" -v ON_ERROR_STOP=1',
        ],
        input=sql,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return result.stdout


def explain(sql: str) -> str:
    # Run twice and keep the second plan, so the buffer cache is warm in both measurements.
    psql(f"EXPLAIN (ANALYZE, BUFFERS) {sql};")
    return psql(f"EXPLAIN (ANALYZE, BUFFERS) {sql};").rstrip()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    psql(CLEANUP)  # leftovers of an interrupted run
    psql(SEED)
    try:
        psql(DROP_INDEXES)
        before = [explain(sql) for _, _, sql in QUERIES]
        psql(CREATE_INDEXES)
        after = [explain(sql) for _, _, sql in QUERIES]
    finally:
        psql(CREATE_INDEXES)
        psql(CLEANUP)

    lines = [
        "# EXPLAIN (ANALYZE, BUFFERS): before and after the Lab 7 indexes",
        "",
        f"Data set: {STATIONS} stations, {VEHICLES:,} vehicles, {RENTERS:,} renters, "
        f"{RENTALS:,} rentals (PostgreSQL 16, generated by `scripts/explain_lab7.py`).",
        "",
    ]
    for (title, source, sql), plan_before, plan_after in zip(QUERIES, before, after, strict=True):
        lines += [
            f"## {title}",
            "",
            f"Source: {source}",
            "",
            "```sql",
            sql,
            "```",
            "",
            "**Before (no index):**",
            "",
            "```",
            plan_before,
            "```",
            "",
            "**After (index):**",
            "",
            "```",
            plan_after,
            "```",
            "",
        ]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
